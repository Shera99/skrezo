"""Интерфейс распознавания речи (§11 ТЗ ассистента).

Значительная часть наших пациентов пишет голосом — особенно старшее поколение
и кыргызоязычные; ассистент, не понимающий голосовые, для этой группы просто
не работает. Провайдер вынесен за интерфейс: выбор конкретного сервиса —
отдельное решение (замер доли голосовых и тест качества на кыргызском).

Ключевое правило раздела зашито в тип результата: вместе с текстом провайдер
обязан вернуть **уверенность**. Низкая уверенность или пустой текст уводят
сообщение в эскалацию, а не в догадку — ошибка расшифровки на входе даёт
уверенно неправильный ответ на выходе, худший из возможных сценариев.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import Protocol


class SpeechError(RuntimeError):
    """Провайдер не смог обработать запрос (сеть, квота, отказ сервиса)."""


@dataclass(frozen=True, slots=True)
class SpeechResult:
    """Расшифровка и уверенность в ней (0..1)."""

    text: str
    confidence: float


class SpeechProvider(Protocol):
    """Контракт распознавания: аудио на входе, текст с уверенностью на выходе."""

    model_name: str

    async def transcribe(
        self, audio: bytes, mime: str, lang_hint: str | None = None
    ) -> SpeechResult:
        """Расшифровать запись; ``SpeechError`` — если не получилось вовсе."""
        ...
