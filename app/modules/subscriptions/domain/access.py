"""Что клинике позволено при её статусе подписки.

Правило считается **по датам подписки, а не по факту прогона джобы**: и триал, и
оплаченный период кончаются в конкретный момент, даже если воркер лежит. Иначе
упавший воркер означал бы бесплатный доступ — а это ровно тот случай, когда
ошибка инфраструктуры молча превращается в потерю денег.

Симметрия здесь не украшение. Раньше по дате считался только триал, а
оплаченный период — по статусу: клиника с давно кончившимся периодом сохраняла
полный доступ, пока кто-нибудь не сменит ей статус вручную.

Закрытая подписка не выключает клинику целиком: чтение остаётся. Клиника видит
своих пациентов, расписание и историю, но не заводит новые приёмы и не проводит
платежи. Полное отключение оставило бы её без данных в разгар рабочего дня.

Даты обоих сроков — только именованные аргументы: перепутать местами два
``datetime`` в вызове слишком легко, а цена ошибки — открытый или закрытый
доступ не тому.
"""

from __future__ import annotations

import enum
from datetime import datetime

from app.shared.db.enums import SubscriptionStatus


class ClinicAccess(enum.StrEnum):
    """Уровень доступа клиники при текущем состоянии подписки."""

    FULL = "full"
    READ_ONLY = "read_only"


def clinic_access(
    status: SubscriptionStatus,
    now: datetime,
    *,
    trial_ends_at: datetime | None,
    current_period_end: datetime | None,
) -> ClinicAccess:
    """Полный доступ или только чтение.

    Полный — у **не истёкшего** триала и у оплаченной подписки, чей период ещё
    не кончился. Всё остальное (истёкший триал или период, ожидание карты,
    просрочка платежа, ручной блок, уход клиента) — только чтение.

    ``active`` без даты конца периода считается действующим: такую запись
    создаёт только правка руками в БД, а закрывать доступ из-за незаполненного
    поля — худший способ узнать о нём. Ручка активации дату требует всегда.
    """
    if status is SubscriptionStatus.ACTIVE:
        return _access_until(current_period_end, now)
    if status is SubscriptionStatus.TRIAL:
        return _access_until(trial_ends_at, now)
    return ClinicAccess.READ_ONLY


def _access_until(deadline: datetime | None, now: datetime) -> ClinicAccess:
    """Доступ до срока; срока нет — считаем действующим."""
    if deadline is not None and deadline <= now:
        return ClinicAccess.READ_ONLY
    return ClinicAccess.FULL
