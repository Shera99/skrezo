"""Текст сообщения сотруднику о добавлении в клинику.

Текст решает домен, а не канал: он один на WhatsApp и SMS. Латиницей, как код
подтверждения, его писать смысла нет — в сообщении есть название клиники, а оно
кириллицей, и сегмент всё равно считается по UCS-2.

Временный пароль намеренно идёт в сообщении: без него уведомление сводится к
«вас добавили, спросите пароль у администратора». Пароль одноразовый по смыслу —
аккаунт помечен ``must_change_password`` и потребует смены при первом входе.
"""

from __future__ import annotations


def staff_added_text(*, clinic_name: str, phone: str, temp_password: str) -> str:
    """Сообщение «вас добавили в клинику» с данными для входа."""
    return (
        f"Skrezo: вас добавили в клинику «{clinic_name}». "
        f"Вход по номеру {phone}, временный пароль: {temp_password}. "
        "Смените его при первом входе."
    )
