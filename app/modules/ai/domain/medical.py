"""Медицинский фильтр (§9 ТЗ) — детерминированный классификатор ДО модели.

Два разных случая, и путать их нельзя:

* **Жалоба на состояние** (§9.1) — «болит», «ноет», «нормально ли это».
  Ассистент не обсуждает состояние ни в какой форме, даже если способен
  ответить верно: правильный по существу ответ, данный ботом, — это
  медицинская консультация без лицензии. Шаблон + ближайшие слоты.
* **Сильная боль** без признаков неотложного — «сильно болит зуб», «болит
  всю ночь». Для стоматологии это самая частая причина записи, а не повод
  останавливать бота (решение владельца 12.10.2026): шаблон с ближайшим
  временем — сегодня, если есть, — и уведомление администратору. Диалог
  остаётся у бота, пациент записывается дальше.
* **Неотложное состояние** (§9.2) — отёк, кровотечение, травма, гной,
  температура, не открывается рот. Реакция немедленная и минуя модель:
  телефон клиники, срочное уведомление администратору, никакого диалога и
  никаких уточняющих вопросов.

Список неотложных **намеренно избыточен**: ложное срабатывание стоит одного
лишнего звонка, пропуск — здоровья пациента. Финальную вычитку списка ждём
от практикующего стоматолога (пункт «вне кода» в дорожной карте); до неё
работает этот стартовый набор, собранный по §9.2.

Диагнозы (кариес, пульпит) в триггеры жалоб НЕ входят: это ещё и названия
услуг прайса, и на вопросе «сколько стоит лечение кариеса» фильтр не должен
подменять прайс шаблоном про врача.
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from enum import StrEnum


class MedicalKind(StrEnum):
    """Что фильтр увидел в сообщении пациента."""

    NONE = "none"
    COMPLAINT = "complaint"  # §9.1 — жалоба на состояние
    ACUTE_PAIN = "acute_pain"  # сильная боль: ближайшее время + администратор
    URGENT = "urgent"  # §9.2 — неотложное


@dataclass(frozen=True, slots=True)
class MedicalVerdict:
    """Вердикт фильтра; ``label`` — что именно сработало (в журнал и эскалацию)."""

    kind: MedicalKind
    label: str | None = None


#: §9.2. Порядок важен только для метки в журнале — срабатывает первое.
_URGENT: list[tuple[str, re.Pattern[str]]] = [
    ("swelling", re.compile(r"отёк\w*|отек\b|опух\w*|припух\w*|флюс|шиш(ик|ип|кен)\w*", re.I)),
    ("fever", re.compile(r"температур\w*|ысытма", re.I)),
    (
        "bleeding",
        re.compile(
            r"кровотеч\w*|кровоточ\w*|\bкров(ь|и|ью)\b|"
            r"\bкан\b|кан\s+(агып|токтобой)",
            re.I,
        ),
    ),
    (
        "trauma",
        re.compile(
            r"травм\w*|жаракат|(выбил|выбит|сломал|сломан|выпал)\w*\s+зуб|"
            r"зуб\s+(выбил|сломал|выпал)\w*|тиш\w*\s+сын\w*",
            re.I,
        ),
    ),
    (
        "trismus",
        re.compile(r"не\s+открыва\w*\s+рот|рот\s+не\s+открыва\w*|ооз\w*\s+ачыл\w*", re.I),
    ),
    ("pus", re.compile(r"\bгно(й|я|ем|е)\b|гнойн\w*|ириң", re.I)),
]

#: Формы «боли» как состояния: болит, болят, боль, боли, болью, болел(а/о/и).
#: Не ``бол\w*``: иначе «очень большое спасибо» — сильная боль, а «очень больно
#: удалять?» и «сильно болеть будет?» (вопросы о процедуре — их ведёт модель)
#: превращались бы в срочную запись с пушем администратору.
_PAIN_FORMS = r"бол(ит|ят|ь|и|ью|ел|ела|ело|ели)\b"

#: Сильная боль без признаков неотложного — проверяется ПОСЛЕ неотложных.
_ACUTE_PAIN: list[tuple[str, re.Pattern[str]]] = [
    (
        "severe_pain",
        re.compile(
            rf"(сильн|очень|нестерпим|невыносим|ужасн|адск|остр)\w*\s+{_PAIN_FORMS}|"
            rf"{_PAIN_FORMS}(\s+\w+)?\s+(ночью|всю\s+ночь)|катуу\s+оору\w*|"
            r"түн\w*\s+уктай\s+албад\w*",
            re.I,
        ),
    ),
]

#: §9.1. Диагнозов здесь нет намеренно — см. докстринг модуля.
_COMPLAINT: list[tuple[str, re.Pattern[str]]] = [
    # «больно» ловим только в личной форме: «Больно ли удалять?» — вопрос о
    # процедуре, а не жалоба на состояние, и отвечать на него должна модель
    # (за обещание «не больно» отвечает валидатор V04, а не этот фильтр).
    (
        "pain",
        re.compile(
            r"\bбол(ит|ят|ел|ела|ело|и)\b|\bболь\b|мне\s+больно|"
            r"больно\s+(жевать|глотать|кусать|есть|пить|нажимать|дотраг\w*)|"
            r"ноет|ноющ\w*",
            re.I,
        ),
    ),
    (
        "discomfort",
        re.compile(r"беспоко\w*|тревож\w*|дискомфорт|неприятн\w*\s+ощущ\w*", re.I),
    ),
    (
        "sensitivity",
        re.compile(r"чувствительн\w*|реагиру\w*\s+на\s+(холодн|горяч|сладк)", re.I),
    ),
    (
        "asks_norm",
        re.compile(r"нормально\s+ли|это\s+нормально|что\s+со\s+мной|что\s+это\s+(може|тако)", re.I),
    ),
    ("ky_pain", re.compile(r"оору(йт|п|м|ду)\w*|тынчсыздандыр\w*", re.I)),
]


def classify(text: str) -> MedicalVerdict:
    """Отнести сообщение пациента к жалобе, неотложному или ни к чему.

    Неотложное проверяется первым: «сильная боль и опухла щека» — это §9.2,
    а не сильная боль, и отвечать на такое подбором слотов нельзя. Сильная
    боль — раньше обычной жалобы: ей нужно время сегодня и администратор.
    """
    if not text or not text.strip():
        return MedicalVerdict(MedicalKind.NONE)
    for label, pattern in _URGENT:
        if pattern.search(text):
            return MedicalVerdict(MedicalKind.URGENT, label)
    for label, pattern in _ACUTE_PAIN:
        if pattern.search(text):
            return MedicalVerdict(MedicalKind.ACUTE_PAIN, label)
    for label, pattern in _COMPLAINT:
        if pattern.search(text):
            return MedicalVerdict(MedicalKind.COMPLAINT, label)
    return MedicalVerdict(MedicalKind.NONE)
