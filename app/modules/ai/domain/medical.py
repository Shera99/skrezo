"""Медицинский фильтр (§9 ТЗ) — детерминированный классификатор ДО модели.

Два разных случая, и путать их нельзя:

* **Жалоба на состояние** (§9.1) — «болит», «ноет», «нормально ли это».
  Ассистент не обсуждает состояние ни в какой форме, даже если способен
  ответить верно: правильный по существу ответ, данный ботом, — это
  медицинская консультация без лицензии. Шаблон + ближайшие слоты.
* **Сильная боль** без признаков неотложного — «сильно болит зуб», «болит
  всю ночь», «мне очень больно». Для стоматологии это самая частая причина
  записи, а не повод останавливать бота (решение владельца 12.10.2026):
  шаблон с ближайшим временем — сегодня, если есть, — и уведомление
  администратору. Диалог остаётся у бота, пациент записывается дальше.
* **Неотложное состояние** (§9.2) — отёк, кровотечение, травма, гной,
  температура, не открывается рот. Реакция немедленная и минуя модель:
  телефон клиники, срочное уведомление администратору, никакого диалога и
  никаких уточняющих вопросов. Ловим по основе слова, а не по словарной
  форме: «щека отекла», «десна распухла», «кровит десна» — тот же отёк и то
  же кровотечение.

«Больно» — наречие, и в нём жалобу легко спутать с вопросом о процедуре
(«больно удалять?»). Правило: «больно» — состояние, если за ним не идёт
вопрос («больно?», «больно ли…», «больно будет…», «больно + инфинитив»,
кроме симптомов вроде «больно жевать»). С усилителем («мне очень больно»,
«очень больно, зуб») — это **сильная боль**: «очень больно» значит то же,
что «очень болит», и разводить их по разным веткам было бы непоследовательно.
Без усилителя — обычная **жалоба**, и только в личной форме («мне больно»)
или с симптомом («больно жевать»): голое «это больно» чаще вопрос, чем
жалоба. Отрицание снимает усилитель: «не очень больно» — не сильная боль.

Список неотложных **намеренно избыточен**: ложное срабатывание стоит одного
лишнего звонка, пропуск — здоровья пациента. Финальную вычитку списка ждём
от практикующего стоматолога (пункт «вне кода» в дорожной карте); до неё
работает этот стартовый набор, собранный по §9.2.

Диагнозы (кариес, пульпит) в триггеры жалоб НЕ входят: это ещё и названия
услуг прайса, и на вопросе «сколько стоит лечение кариеса» фильтр не должен
подменять прайс шаблоном про врача.
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from enum import StrEnum


class MedicalKind(StrEnum):
    """Что фильтр увидел в сообщении пациента."""

    NONE = "none"
    COMPLAINT = "complaint"  # §9.1 — жалоба на состояние
    ACUTE_PAIN = "acute_pain"  # сильная боль: ближайшее время + администратор
    URGENT = "urgent"  # §9.2 — неотложное


@dataclass(frozen=True, slots=True)
class MedicalVerdict:
    """Вердикт фильтра; ``label`` — что именно сработало (в журнал и эскалацию)."""

    kind: MedicalKind
    label: str | None = None


#: §9.2. Порядок важен только для метки в журнале — срабатывает первое.
#: Отёк и кровотечение ловим по основе, а не по словарной форме: пациент
#: пишет «щека отекла», «десна распухла», «кровит десна», а не «отёк» и
#: «кровотечение». ``\b`` перед основой обязателен: без него «отек» находится
#: внутри «ипотеки» и «дискотеки»; «отечн» (а не «отеч») — чтобы «отёчный»
#: не путался с «отечественный» («импланты отечественные?» — не отёк).
_URGENT: list[tuple[str, re.Pattern[str]]] = [
    (
        "swelling",
        re.compile(
            # отёк, отекла, отекло, отёкшая, отекает; отёчный, отёчность
            r"\bот[её]к\w*|\bот[её]чн\w*|"
            # опухла, распухло, вспухла, припухлость, опухшая; пухнет
            r"\b(?:о|рас|вс|при|под)пух\w*|\bпухн\w*|"
            r"флюс|шиш(ик|ип|кен)\w*",
            re.I,
        ),
    ),
    ("fever", re.compile(r"температур\w*|ысытма", re.I)),
    (
        "bleeding",
        re.compile(
            r"кровотеч\w*|кровоточ\w*|\bкров(ь|и|ью)\b|"
            # кровит, кровят, кровила, кровить, кровящая, закровила — но не «кровать»
            r"\b(?:за)?кров(?:ит|ят|ил[аои]?|ить|ящ\w*)\b|"
            r"\bкан\b|кан\s+(агып|токтобой)",
            re.I,
        ),
    ),
    (
        "trauma",
        re.compile(
            r"травм\w*|жаракат|(выбил|выбит|сломал|сломан|выпал)\w*\s+зуб|"
            r"зуб\s+(выбил|сломал|выпал)\w*|тиш\w*\s+сын\w*",
            re.I,
        ),
    ),
    (
        "trismus",
        re.compile(r"не\s+открыва\w*\s+рот|рот\s+не\s+открыва\w*|ооз\w*\s+ачыл\w*", re.I),
    ),
    ("pus", re.compile(r"\bгно(й|я|ем|е)\b|гнойн\w*|ириң", re.I)),
]

#: Формы «боли» как состояния: болит, болят, боль, боли, болью, болел(а/о/и).
#: Не ``бол\w*``: иначе «очень большое спасибо» — сильная боль, а «сильно
#: болеть будет?» (вопрос о процедуре — его ведёт модель) превращался бы в
#: срочную запись с пушем администратору.
_PAIN_FORMS = r"бол(ит|ят|ь|и|ью|ел|ела|ело|ели)\b"

#: Инфинитивы-симптомы: «больно жевать» — жалоба на состояние, а не вопрос.
_SYMPTOM_VERBS = r"жевать|глотать|кусать|есть|пить|нажимать|дотраг\w*|открыва\w*"

#: «Больно» как состояние: «мне очень больно», «очень больно, зуб», «больно
#: жевать». Вопрос о процедуре — «больно?», «больно ли…», «больно будет…»,
#: «больно + инфинитив» («очень больно удалять зуб мудрости?») — сюда не
#: попадает: его ведёт модель, а обещание «не больно» ловит валидатор V04.
#: Обратный порядок без «?» («удалять очень больно») от жалобы не отличить;
#: цена такой ошибки — лишнее уведомление администратору.
_PAINFUL_STATE = (
    r"больно(?!\s*\?|\s+(?:ли|будет)\b|"
    rf"\s+(?!(?:{_SYMPTOM_VERBS})\b)\w+(?:ть|ться|ти)\b)"
)

#: Усилитель боли. ``(?<!\bне\s)``: «не очень больно», «не сильно болит» —
#: как раз не сильная боль (обычная жалоба или отзыв после приёма).
_INTENSIFIER = r"(?<!\bне\s)\b(?:сильн|очень|нестерпим|невыносим|ужасн|адск|остр)\w*"

#: Сильная боль без признаков неотложного — проверяется ПОСЛЕ неотложных.
_ACUTE_PAIN: list[tuple[str, re.Pattern[str]]] = [
    (
        "severe_pain",
        re.compile(
            rf"{_INTENSIFIER}\s+(?:{_PAIN_FORMS}|{_PAINFUL_STATE})|"
            rf"{_PAIN_FORMS}(\s+\w+)?\s+(ночью|всю\s+ночь)|катуу\s+оору\w*|"
            r"түн\w*\s+уктай\s+албад\w*",
            re.I,
        ),
    ),
]

#: §9.1. Диагнозов здесь нет намеренно — см. докстринг модуля.
_COMPLAINT: list[tuple[str, re.Pattern[str]]] = [
    # «Больно» без усилителя ловим только в личной форме и с симптомом: голое
    # «это больно» или «больно ли удалять?» — вопрос о процедуре, а не жалоба.
    (
        "pain",
        re.compile(
            rf"\bбол(ит|ят|ел|ела|ело|и)\b|\bболь\b|мне\s+{_PAINFUL_STATE}|"
            rf"больно\s+(?:{_SYMPTOM_VERBS})\b|ноет|ноющ\w*",
            re.I,
        ),
    ),
    (
        "discomfort",
        re.compile(r"беспоко\w*|тревож\w*|дискомфорт|неприятн\w*\s+ощущ\w*", re.I),
    ),
    (
        "sensitivity",
        re.compile(r"чувствительн\w*|реагиру\w*\s+на\s+(холодн|горяч|сладк)", re.I),
    ),
    (
        "asks_norm",
        re.compile(r"нормально\s+ли|это\s+нормально|что\s+со\s+мной|что\s+это\s+(може|тако)", re.I),
    ),
    ("ky_pain", re.compile(r"оору(йт|п|м|ду)\w*|тынчсыздандыр\w*", re.I)),
]


def classify(text: str) -> MedicalVerdict:
    """Отнести сообщение пациента к жалобе, неотложному или ни к чему.

    Неотложное проверяется первым: «сильная боль и опухла щека» — это §9.2,
    а не сильная боль, и отвечать на такое подбором слотов нельзя. Сильная
    боль — раньше обычной жалобы: ей нужно время сегодня и администратор.
    """
    if not text or not text.strip():
        return MedicalVerdict(MedicalKind.NONE)
    for label, pattern in _URGENT:
        if pattern.search(text):
            return MedicalVerdict(MedicalKind.URGENT, label)
    for label, pattern in _ACUTE_PAIN:
        if pattern.search(text):
            return MedicalVerdict(MedicalKind.ACUTE_PAIN, label)
    for label, pattern in _COMPLAINT:
        if pattern.search(text):
            return MedicalVerdict(MedicalKind.COMPLAINT, label)
    return MedicalVerdict(MedicalKind.NONE)
