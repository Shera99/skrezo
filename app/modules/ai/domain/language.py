def detect_lang(text: str | None) -> str | None:
    """``ru`` / ``ky`` — если язык сообщения ясен; ``None`` — признаков не хватает."""
    guess = guess_lang(text)
    return guess.lang if guess is not None else None


def guess_lang(text: str | None) -> LangGuess | None:
    """Язык сообщения и уверенность в нём; ``None`` — признаков не хватает.

    Уверенно (``strong``) — у победителя не меньше двух очков и у другого языка
    ни одного, либо перевес вдвое и хотя бы на два очка. Иначе догадка слабая:
    одно русское слово («Здравствуйте») или одно кыргызское, набранное без
    ү/ө/ң («Бугун»), — не повод переключать идущий диалог.
    """
    if not text or not text.strip():
        return None
    ky = float(len(_KY_AFTER_NUMBER.findall(text)))
    ru = 0.0
    for raw in _WORD.findall(text):
        word = raw.lower().replace("ё", "е")
        if word in _LOANWORDS:
            continue  # «запись», «пломба» пишут и по-кыргызски — не признак
        if word in _RU_WORDS:
            ru += 1
        elif word in _KY_WEAK:
            ky += 0.5
        elif word in _KY_WORDS:
            ky += 2  # надёжный признак: одного слова хватает
        elif _KY_LETTERS.search(word) and not raw[0].isupper():
            # С заглавной и не из словаря — скорее имя («Айгүл»), не язык.
            ky += 2
        elif word in _KY_WORDS_TYPED or (_KY_SUFFIX.search(word) and word not in _RU_LOOKALIKES):
            ky += 1
    if ky >= 1 and ky > ru:
        return LangGuess(KY, _is_strong(ky, ru))
    if ru > ky:
        return LangGuess(RU, _is_strong(ru, ky))
    return None


def _is_strong(winner: float, loser: float) -> bool:
    """Уверенная ли победа: два очка при нуле у другого или перевес вдвое на два очка."""
    if loser == 0:
        return winner >= 2
    return winner >= 2 * loser and winner - loser >= 2
