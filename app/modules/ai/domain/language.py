"""Язык сообщения пациента: русский или кыргызский (§10.2).

Ассистент отвечает на языке ПОСЛЕДНЕГО сообщения пациента, а не того, на
котором начался диалог: человек написал «Саламатсызбы» после русской
переписки — дальше говорим по-кыргызски. Раньше язык фиксировался первым
ответом бота навсегда, и на кыргызскую реплику бот отвечал по-русски.

Детектор детерминированный и осторожный — он решает, только когда уверен:

* считаем очки каждого языка и берём большинство. Кыргызские признаки двух
  сортов: **надёжные** (слово с буквами ``ң ө ү`` — в русском их нет — или из
  словаря частых слов) — два очка, одного такого слова хватает для
  уверенности; **слабые** (слово, набранное без этих букв: «бугун», «дагы»;
  характерное окончание: «-сузбу», «-уп/-ып»; окончание после числа: «11 ден»,
  «15ке») — очко: так пишет большинство пациентов с телефона, но и русское
  слово изредка похоже. Русское слово из своего словаря — очко;
* заимствования («запись», «пломба») пишут в обеих фразах — они очков не дают,
  а русские слова, похожие на кыргызские окончания («приступ», «скрип»), —
  исключения;
* догадка **уверенная**, когда у победителя не меньше двух очков при нуле у
  другого языка или перевес вдвое и хотя бы на два очка. Слабая догадка язык
  уже идущего диалога не переключает: язык выбирает модель (§10.2);
* буквы дают очко СЛОВУ, а не всему сообщению, и только слову со строчной
  буквы или из словаря: слово с заглавной вне словаря — скорее имя. «Я
  Гүлнара, запишите на завтра» и ответ «Айгүл» на «как вас зовут?» — не повод
  переходить на кыргызский;
* «рахмат», «ооба», «жок» говорят и русскоязычные — в одиночку они язык не
  переключают (половина очка), нужно ещё хотя бы одно кыргызское слово;
* ничья (имя, число, «ок», смешанная фраза поровну) — ``None``: язык диалога
  не меняется, и одна реплика без признаков не переключает разговор.

Казахский с теми же буквами тоже уйдёт в ``ky`` — ассистент знает только два
языка, а из них кыргызский казахскому ближе.
"""

