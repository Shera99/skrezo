def detect_lang(text: str | None) -> str | None:
    """``ru`` / ``ky`` — если язык сообщения ясен; ``None`` — признаков не хватает."""
    if not text or not text.strip():
        return None
    ky = 0.0
    ru = 0
    for raw in _WORD.findall(text):
        word = raw.lower().replace("ё", "е")
        if word in _RU_WORDS:
            ru += 1
        elif word in _KY_WEAK:
            ky += 0.5
        elif word in _KY_WORDS:
            ky += 1
        elif _KY_LETTERS.search(word) and not raw[0].isupper():
            # С заглавной и не из словаря — скорее имя («Айгүл»), не язык.
            ky += 1
    if ky >= 1 and ky > ru:
        return KY
    if ru > ky:
        return RU
    return None
