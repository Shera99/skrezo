"""Длительность приёма: время услуги задано НА ОДИН ЗУБ.

Клиника заводит услугу с длительностью одной процедуры — «лечение кариеса, 40
минут». Это время **одного зуба**: три зуба за приём врач лечит втрое дольше.
Пока длительность бралась только из ``appointment.service_id``, запись на три
зуба занимала слот одного — и следующий пациент приходил в занятое кресло.

Единица счёта у позиции — **зуб**, если зубы указаны, иначе ``quantity``. У
работ по зубу количество единиц задают именно зубы (мост на 35–37 — три единицы
времени при одной цене), у работ вне зуба (чистка, снимок, консультация) —
поле ``quantity``. Перемножать оба нельзя: регистратор, заполнивший и
``quantity: 2``, и два зуба, получил бы вчетверо больший приём.

Позиции без известной длительности (услуга не выбрана либо у неё не задана
``duration``) времени не добавляют: сочинять им дефолт значит раздувать приём
на ровном месте. Если таких позиций весь чек — считать не по чему, и
длительность берётся по-старому: из услуги приёма, иначе дефолт.
"""

from __future__ import annotations

import uuid
from collections.abc import Mapping, Sequence

from app.modules.appointments.domain.models import ItemInput

# Верхняя граница длительности приёма — сутки. Она же потолок расчёта по
# позициям: без неё чек на два десятка зубов молча растягивает карточку за
# пределы дня, и приём перестаёт помещаться в любое рабочее окно.
MAX_DURATION_MIN = 24 * 60


def item_units(teeth_count: int, quantity: int) -> int:
    """Сколько раз процедура выполняется в позиции: зубы, иначе ``quantity``."""
    if teeth_count > 0:
        return teeth_count
    return max(quantity, 1)


def duration_from_items(
    items: Sequence[ItemInput], durations: Mapping[uuid.UUID, int | None]
) -> int | None:
    """Длительность приёма по составу; ``None`` — считать не по чему.

    ``durations`` — длительности услуг позиций (минуты на одну процедуру),
    ``None`` у услуги без заданной длительности.
    """
    total = 0
    for item in items:
        if item.service_id is None:
            continue
        base = durations.get(item.service_id)
        if not base:
            continue
        # Зуб, названный в позиции дважды, — один зуб: так же считает и запись
        # позиций в БД (``dict.fromkeys`` в ``_write_items``).
        total += base * item_units(len(set(item.teeth)), item.quantity)
    return total or None
