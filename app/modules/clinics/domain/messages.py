"""Текст сообщения владельцу о созданном кабинете клиники.

Клинику заводит команда Skrezo, и владелец должен узнать, что кабинет готов и
как в него попасть. Пароля в сообщении нет: вход по коду, который владелец
запрашивает сам, — передавать секрет сообщением больше не нужно.
"""

from __future__ import annotations


def clinic_created_text(*, clinic_name: str, phone: str) -> str:
    """Сообщение «кабинет создан» с данными для входа."""
    return (
        f"Skrezo: кабинет клиники «{clinic_name}» создан. "
        f"Вход по номеру {phone} — запросите код подтверждения на этот номер."
    )
