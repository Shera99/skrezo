"""Текст сообщения владельцу о созданном кабинете клиники.

Клинику заводит команда Skrezo, и до этого сообщения владелец о своём временном
пароле узнавал только голосом от менеджера. Пароль потребует смены при первом
входе (``must_change_password``), поэтому его отправка сообщением — не хранение
секрета, а разовая передача.
"""

from __future__ import annotations


def clinic_created_text(*, clinic_name: str, phone: str, temp_password: str) -> str:
    """Сообщение «кабинет создан» с данными для входа."""
    return (
        f"Skrezo: кабинет клиники «{clinic_name}» создан. "
        f"Вход по номеру {phone}, временный пароль: {temp_password}. "
        "Смените его при первом входе."
    )
